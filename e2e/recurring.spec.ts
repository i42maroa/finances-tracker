  await openRecurring(page);
  await page.getByRole('button', { name: 'Añadir recurrente' }).click();
  let dialog = page.getByRole('dialog', { name: 'Añadir movimiento recurrente' });
  await dialog.getByRole('tab', { name: 'Ingreso', exact: true }).click();
  await dialog.getByLabel('Nombre', { exact: true }).fill('Nómina recurrente');
  await dialog.getByLabel('Importe (€)', { exact: true }).fill('1500');
  await dialog.getByLabel('Desde', { exact: true }).fill('2026-10-01');
  await dialog.getByLabel('Hasta', { exact: false }).fill('2026-09-01');
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(dialog.getByRole('alert')).toHaveText('Revisa las fechas de inicio y fin.');
