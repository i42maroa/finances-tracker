import { test, expect, Page } from '@playwright/test';
import { openSecondaryMenu, clickSecondary } from './secondary-menu';

test.use({ timezoneId: 'Europe/Madrid' });
test.beforeEach(async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-19T12:00:00+01:00'));
  await page.route('**/firebase-config.test.json', route => route.fulfill({ json: { apiKey: '', authDomain: '', projectId: '', appId: '' } }));
  await page.goto('/');
  await page.getByRole('button', { name: /Explorar la demostra/ }).click();
  await expect(page.getByRole('heading', { name: 'Movimientos del mes', exact: true })).toBeVisible();
});

async function openRecurring(page: Page) {
  await openSecondaryMenu(page);
  const menu = page.getByRole('dialog', { name: 'Menú', exact: true });
  await (await menu.isVisible() ? menu : page.getByRole('navigation', { name: 'Navegación principal', exact: true })).getByRole('link', { name: 'Recurrentes', exact: true }).click();
}
async function goMonth(page: Page, month: string) {
  await page.goto(`/resumen/${month}`);
  await page.getByRole('button', { name: /Explorar la demostra/ }).click();
  await expect(page.getByRole('heading', { name: 'Movimientos del mes', exact: true })).toBeVisible();
}
async function openPlanned(page: Page) {
  await openSecondaryMenu(page);
  await page.getByRole('group', { name: 'Operaciones del mes', exact: true }).getByRole('link', { name: 'Gastos previstos', exact: true }).click();
}
async function goPlanned(page: Page, month: string) { await goMonth(page, month); await openPlanned(page); }
async function backToMonth(page: Page) { await page.getByRole('navigation', { name: 'Ruta de navegación' }).getByRole('link').last().click(); }

test('un pago realizado en otro mes conserva su ficha en el mes previsto y se puede abrir desde el año', async ({ page }) => {
  await page.evaluate(() => {
    const data = JSON.parse(localStorage.getItem('hucha-demo-v1')!);
    const original = data.movements.find((item: { id: string }) => item.id === '2');
    const { date, ...fields } = original;
    const recurring = { ...fields, id: 'paid-netflix', concept: 'Netflix confirmado', amountCents: 900, description: '', startDate: '2026-11-01', endDate: '2026-11-30', days: [2], enabled: true, effectiveFrom: '2026-11-01', revision: 1, history: [] };
    data.recurringMovements = [recurring];
    data.movements = [{ ...original, id: 'recurring-paid-netflix-2026-11-02', concept: recurring.concept, amountCents: 900, recurringId: recurring.id, scheduledDate: '2026-11-02', date: '2026-12-05', status: 'confirmed' }];
    localStorage.setItem('hucha-demo-v1', JSON.stringify(data));
  });
  await goPlanned(page, '2026-11');
  const row = page.getByRole('article', { name: 'Netflix confirmado', exact: true });
  await expect(row).toContainText('Pagado');
  await expect(row).toContainText('Fecha prevista: 2 nov');
  await expect(row).toContainText('Pagado el 5 dic 2026');
  await expect(row).toContainText('30 nov 2026');
  await expect(page.locator('.planned-totals .expense-amount')).toHaveText('0,00 €');
  await backToMonth(page);
  await expect(page.locator('.stat-value').nth(1)).toHaveText('0,00 €');
  await page.getByRole('navigation', { name: 'Ruta de navegación' }).getByRole('link', { name: '2026', exact: true }).click();
  await expect(page.getByRole('link', { name: 'noviembre', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'noviembre', exact: true }).click();
  await openPlanned(page);
  await expect(row).toContainText('Pagado');
});

test('al corregir el inicio de Netflix del 19 al 1 aparece el gasto previsto del día 2', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 900 });
  await openRecurring(page);
  await page.getByRole('button', { name: 'Añadir recurrente' }).click();
  let dialog = page.getByRole('dialog', { name: 'Añadir movimiento recurrente', exact: true });
  await dialog.getByLabel('Nombre', { exact: true }).fill('Netflix');
  await dialog.getByLabel('Importe (€)', { exact: true }).fill('9');
  await expect(dialog.getByLabel('Desde', { exact: true })).toHaveValue('2026-11-19');
  await dialog.getByRole('checkbox', { name: 'Día 19', exact: true }).uncheck();
  await dialog.getByRole('checkbox', { name: 'Día 2', exact: true }).check();
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await goPlanned(page, '2026-11');
  await expect(page.getByRole('article', { name: 'Netflix', exact: true })).toHaveCount(0);
  await openRecurring(page);
  await page.getByRole('article', { name: 'Netflix', exact: true }).getByRole('button', { name: 'Editar recurrencia' }).click();
  dialog = page.getByRole('dialog', { name: 'Editar movimiento recurrente', exact: true });
  await dialog.getByLabel('Desde', { exact: true }).fill('2026-11-01');
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await goMonth(page, '2026-11');
  await expect(page.getByRole('status', { name: 'Movimientos previstos por gestionar' })).toContainText('Tienes un movimiento previsto por gestionar');
  await openPlanned(page);
  const row = page.getByRole('article', { name: 'Netflix', exact: true });
  await expect(row).toHaveCount(1);
  await expect(row).toContainText('2 nov');
  await expect(row).toContainText('9,00');
  await expect(row).toContainText('Pendiente de pago');
  await row.getByRole('button', { name: 'Marcar como pagado' }).click();
  await page.getByRole('dialog', { name: 'Confirmar pago' }).getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(row).toContainText('Pagado');
  await expect(row).toContainText('Sin fecha de fin');
  await expect(row).toContainText('2 de cada mes');
  await expect(row.getByRole('button', { name: 'Marcar como pagado' })).toHaveCount(0);
  await goPlanned(page, '2026-11');
  await expect(row).toContainText('Pagado');
  await row.getByRole('link', { name: 'Ver movimiento' }).click();
  await expect(page.getByRole('navigation', { name: 'Ruta de navegación' }).locator('li')).toContainText(['Resumen', '2026', 'noviembre', 'Gastos previstos', 'Netflix']);
  await page.reload();
  await page.getByRole('button', { name: /Explorar la demostra/ }).click();
  await page.getByRole('navigation', { name: 'Ruta de navegación' }).getByRole('link', { name: 'Gastos previstos', exact: true }).click();
  await expect(row).toContainText('Pagado');
  await backToMonth(page);
  await expect(page.getByRole('link', { name: 'Netflix', exact: true })).toHaveCount(1);
});

