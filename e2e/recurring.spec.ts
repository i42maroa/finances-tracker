    await expect(page.getByRole('article', { name: 'Internet recurrente', exact: true })).toContainText('40,00');
    await page.getByRole('article', { name: 'Internet recurrente', exact: true }).getByRole('button', { name: 'Omitir esta aparición' }).click();
    await expect(page.getByRole('article', { name: 'Internet recurrente', exact: true })).toHaveCount(0);
    await goPlanned(page, '2026-12');
    await expect(page.getByRole('article', { name: 'Internet recurrente', exact: true })).toHaveCount(0);
    const state = await page.evaluate(() => JSON.parse(localStorage.getItem('hucha-demo-v1')!));
    expect(state.movements.filter((item: { recurringId?: string; status: string }) => item.recurringId && item.status === 'confirmed')).toHaveLength(1);
    expect(state.movements.filter((item: { recurringId?: string; status: string }) => item.recurringId && item.status === 'skipped')).toHaveLength(1);
