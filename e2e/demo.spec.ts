test('gestiona categorías y subcategorías desde el detalle con breadcrumb', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await openSettings(page);
  await clickSecondary(page, page.getByRole('group', { name: 'Opciones de configuración' }).getByRole('link', { name: 'Categorías', exact: true }));
  await expect(page.locator('.category-family button')).toHaveCount(0);
  await page.getByRole('link', { name: 'Hogar', exact: true }).click();
  const breadcrumb = page.getByRole('navigation', { name: 'Ruta de navegación' });
  await expect(breadcrumb).toHaveText(/Configuración\s*[/]\s*Categorías\s*[/]\s*Hogar/);
  await page.getByRole('button', { name: 'Añadir subcategoría', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('textbox')).toHaveCount(1);
  await expect(dialog.getByRole('combobox')).toHaveCount(0);
  await dialog.getByLabel('Nombre', { exact: true }).fill('Comunidad');
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.locator('.subcategory-row').last()).toHaveText('Comunidad');
  const added = await page.evaluate(() => JSON.parse(localStorage.getItem('hucha-demo-v1')!).categories.find((item: { name: string }) => item.name === 'Comunidad'));
  expect(added).toMatchObject({ parentId: 'home', type: 'expense', icon: '⌂' });
  const actions = page.getByRole('group', { name: 'Acciones de la categoría' });
  await clickSecondary(page, actions.getByRole('button', { name: 'Editar', exact: true }));
  await dialog.getByLabel('Nombre', { exact: true }).fill('Mi hogar');
  await dialog.locator('.edit-subcategory').last().getByRole('textbox').fill('Cuota de comunidad');
  await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Hogar.', exact: true })).toBeVisible();
  await expect(page.locator('.subcategory-row').last()).toHaveText('Comunidad');
  await clickSecondary(page, actions.getByRole('button', { name: 'Editar', exact: true }));
  await dialog.getByLabel('Nombre', { exact: true }).fill('Mi hogar');
  await dialog.locator('.edit-subcategory').last().getByRole('textbox').fill('Luz');
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('Ya existe una categoría con ese nombre');
  await expect(page.getByRole('heading', { name: 'Hogar.', exact: true })).toBeVisible();
  await dialog.locator('.edit-subcategory').last().getByRole('textbox').fill('Cuota de comunidad');
  await dialog.locator('.edit-subcategory').first().getByRole('button', { name: 'Eliminar', exact: true }).click();
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(breadcrumb).toHaveText(/Configuración\s*[/]\s*Categorías\s*[/]\s*Mi hogar/);
  await expect(page.locator('.subcategory-row').last()).toHaveText('Cuota de comunidad');
  await expect(page.locator('.subcategory-row').filter({ hasText: 'Hipoteca' })).toHaveCount(0);
  await page.reload(); await page.getByRole('button', { name: /Explorar la demostra/ }).click();
  await expect(page.getByRole('heading', { name: 'Mi hogar.', exact: true })).toBeVisible();
  await expect(page.locator('.subcategory-row').last()).toHaveText('Cuota de comunidad');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await breadcrumb.getByRole('link', { name: 'Categorías', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Mi hogar', exact: true })).toBeVisible();
});

