async function configure(context: BrowserContext): Promise<void> {
  await context.route('**/firebase-config.test.json', route => route.fulfill({ json: { apiKey: 'demo-api-key', authDomain: 'demo-hucha.firebaseapp.com', projectId: 'demo-hucha', appId: 'demo-app', useEmulators: true } }));
}
async function register(page: Page, name: string, suffix: string): Promise<void> {
  await page.goto('/'); await page.getByRole('button', { name: 'Crea tu cuenta' }).click();
  await page.getByLabel('Tu nombre').fill(name); await page.getByLabel('Correo electrónico').fill(`${name.toLowerCase()}-${suffix}@test.local`); await page.getByLabel('Contraseña', { exact: true }).fill('Test-password-123');
  await page.getByRole('button', { name: 'Crear mi cuenta', exact: false }).click();
  await expect(page.getByRole('heading', { name: 'Nuestra pareja.' })).toBeVisible();
}
