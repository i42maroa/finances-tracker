    const code = await a.locator('.invitation code').innerText();
    await register(b, 'Mario', suffix); await b.getByLabel('Código de invitación').fill(code); await b.getByRole('button', { name: 'Vincular mi cuenta', exact: false }).click();
    await expect(b.getByRole('heading', { name: 'Movimientos del mes', exact: true })).toBeVisible();
    await expect(a.locator('.member').filter({ hasText: 'Mario' })).toBeVisible();
    await a.getByRole('link', { name: 'Resumen', exact: true }).click();
    await a.getByRole('button', { name: 'Añadir movimiento', exact: false }).first().click();
    await a.getByRole('dialog').getByRole('combobox', { name: 'Categoría', exact: true }).selectOption('leisure');
    await a.getByRole('dialog').getByRole('combobox', { name: 'Subcategoría', exact: true }).selectOption('leisure-sub-0');
    await a.getByRole('dialog').getByLabel('Importe').fill('60'); await a.getByRole('dialog').getByLabel('Nombre', { exact: true }).fill('Cena sincronizada');
    await a.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click();
    await expect(a.getByRole('dialog')).not.toBeVisible();
    await expect(b.getByText('Cena sincronizada', { exact: true })).toBeVisible();
    await a.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Liquidaciones', exact: true }).click();
    await expect(a.locator('.debt-amount')).toHaveText('30,00 €');
    await b.getByRole('link', { name: 'Cena sincronizada', exact: true }).click();
    await b.getByRole('button', { name: 'Editar', exact: true }).click();
    await expect(b.getByRole('dialog').getByRole('combobox', { name: 'Subcategoría', exact: true })).toHaveValue('leisure-sub-0');
    await b.getByRole('dialog').getByLabel('Importe').fill('80'); await b.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click();
    await expect(a.locator('.debt-amount')).toHaveText('40,00 €');
    await b.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Liquidaciones', exact: true }).click();
    await b.getByRole('button', { name: 'Registrar liquidación', exact: false }).click();
    await b.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click();
    await expect(a.locator('.debt-amount')).toHaveText('Sin deuda pendiente.');
    await a.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Liquidaciones', exact: false }).click();
    await a.getByRole('button', { name: 'Editar liquidación', exact: true }).click();
    await a.getByRole('dialog').getByLabel('Nota').fill('Editada por la otra persona'); await a.getByRole('dialog').getByRole('button', { name: 'Guardar', exact: true }).click();
    await b.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Liquidaciones', exact: false }).click(); await expect(b.getByText(/Editada por la otra persona/)).toBeVisible();
    await b.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Resumen', exact: true }).click(); await b.getByRole('link', { name: 'Cena sincronizada', exact: true }).click(); await b.getByRole('button', { name: 'Eliminar', exact: true }).click(); await b.getByRole('dialog').getByRole('button', { name: 'Eliminar registro', exact: true }).click();
    await a.getByRole('navigation', { name: 'Navegación principal' }).getByRole('link', { name: 'Resumen', exact: true }).click(); await expect(a.getByText('Cena sincronizada', { exact: true })).not.toBeVisible();
    await a.reload(); await expect(a.getByRole('heading', { name: 'Movimientos del mes', exact: true })).toBeVisible();
    await a.getByRole('button', { name: 'Añadir movimiento', exact: true }).click();
    const dialog = a.getByRole('dialog');
    await dialog.getByRole('tab', { name: 'Ingreso', exact: true }).click();
    await dialog.getByLabel('Nombre', { exact: true }).fill('Ingreso privado Lucia');
    await dialog.getByLabel('Importe').fill('100');
    await expect(dialog.getByRole('combobox', { name: 'Quién lo recibe', exact: true }).locator('option')).toHaveCount(1);
    await dialog.getByRole('button', { name: 'Guardar', exact: true }).click();
